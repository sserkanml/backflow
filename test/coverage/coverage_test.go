//go:build coverage

// Package coverage measures how much of what people change in a cluster
// Backflow can trace back to Git, for real charts. It runs the production Helm
// mapping path (helmmap.FieldsFor and helmmap.Verify) with a renderer that
// shells out to `helm template`; in production Argo CD renders. No cluster is
// needed, only the helm binary.
//
//	make coverage           # run, write REPORT.md, fail on a regression
//	make coverage-update    # also accept the current outcomes as the golden file
package coverage

import (
	"context"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"sort"
	"strings"
	"sync"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "accept the current outcomes as testdata/golden.txt")

const goldenFile = "testdata/golden.txt"

func TestCoverage(t *testing.T) {
	if _, err := exec.LookPath("helm"); err != nil {
		t.Fatalf("the helm binary is needed to render the charts: %v", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 40*time.Minute)
	defer cancel()

	var (
		mu      sync.Mutex
		results []caseResult
		wg      sync.WaitGroup
		errs    []error
	)
	slots := make(chan struct{}, runtime.NumCPU())
	for _, c := range charts {
		wg.Add(1)
		go func() {
			defer wg.Done()
			l, err := load(ctx, c, slots)
			if err == nil {
				var rs []caseResult
				if rs, err = l.runAll(ctx); err == nil {
					mu.Lock()
					results = append(results, rs...)
					mu.Unlock()
				}
			}
			if err != nil {
				mu.Lock()
				errs = append(errs, err)
				mu.Unlock()
			}
		}()
	}
	wg.Wait()
	for _, err := range errs {
		t.Error(err)
	}
	if len(errs) > 0 {
		return
	}
	sort.Slice(results, func(i, j int) bool {
		a, b := results[i], results[j]
		if a.Chart != b.Chart {
			return a.Chart < b.Chart
		}
		if a.Resource != b.Resource {
			return a.Resource < b.Resource
		}
		return a.Scenario < b.Scenario
	})

	if err := os.WriteFile("REPORT.md", []byte(report(results)), 0o644); err != nil { //nolint:gosec // a report
		t.Fatal(err)
	}
	for _, p := range policySets() {
		m, pa, total := tally(results, p.name)
		t.Logf("%-10s %d of %d mapped (%.0f%%), %d partial, %.0f%% mapped or partial", p.name, m, total, pct(m, total), pa, pct(m+pa, total))
	}

	got := golden(results)
	if *update {
		if err := os.WriteFile(goldenFile, []byte(got), 0o644); err != nil { //nolint:gosec // test data
			t.Fatal(err)
		}
		t.Logf("%s updated", goldenFile)
		return
	}
	want, err := os.ReadFile(goldenFile)
	if err != nil {
		t.Fatalf("no golden file (run make coverage-update): %v", err)
	}
	regressions, improvements, changed := compare(parseGolden(string(want)), parseGolden(got))
	for _, s := range improvements {
		t.Logf("IMPROVED: %s", s)
	}
	for _, s := range changed {
		t.Logf("CHANGED (new or gone case): %s", s)
	}
	if len(improvements)+len(changed) > 0 {
		t.Logf("run make coverage-update to accept")
	}
	for _, s := range regressions {
		t.Errorf("REGRESSION: %s", s)
	}
}

func pct(n, total int) float64 {
	if total == 0 {
		return 0
	}
	return 100 * float64(n) / float64(total)
}

// tally counts the cases of a policy: fully mapped, partial, and all.
func tally(results []caseResult, policy string) (mapped, partial, total int) {
	for _, r := range results {
		total++
		switch r.ByPolicy[policy].Result {
		case Mapped:
			mapped++
		case Partial:
			partial++
		}
	}
	return
}

// addOnly are the scenarios that only add something the live object has and Git
// does not. Argo CD does not report such fields on its own.
var addOnly = map[string]bool{"env-add": true, "label-add": true, "nodeselector-add": true, "pod-annotation": true, "toleration": true}

// scenarioLabel is the name of a scenario in the report.
func scenarioLabel(id string) string {
	if addOnly[id] {
		return id + " *"
	}
	return id
}

// report is REPORT.md.
func report(results []caseResult) string {
	var b strings.Builder
	b.WriteString("# Mapping coverage\n\n")
	b.WriteString("Generated by `make coverage`; do not edit. Each row is one change made in the cluster to a resource rendered by a real chart, mapped back to the Application's value files with the production Helm mapping path (the renderer is `helm template`).\n\n")
	b.WriteString("Policies: **default** is a policy with no options (`spec.helm.addOverrides` is on by default); **permissive** adds `allowPartial` and `allowCollateralChanges: [Labels, Annotations]`; **no-overrides** is the default with `addOverrides: false`, which is how mapping worked before overrides existed.\n\n")
	b.WriteString("| Policy | Mapped | Partial | Unmapped | Cases | Mapped % | Mapped or partial % |\n|---|---|---|---|---|---|---|\n")
	for _, p := range policySets() {
		m, pa, total := tally(results, p.name)
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %.0f%% | %.0f%% |\n", p.name, m, pa, total-m-pa, total, pct(m, total), pct(m+pa, total))
	}
	b.WriteString("\n## By chart\n\n| Chart | Cases | Mapped % (default) | Mapped or partial % (permissive) |\n|---|---|---|---|\n")
	byChart := map[string][]caseResult{}
	var names []string
	for _, r := range results {
		if _, ok := byChart[r.Chart]; !ok {
			names = append(names, r.Chart)
		}
		byChart[r.Chart] = append(byChart[r.Chart], r)
	}
	for _, n := range names {
		m, _, total := tally(byChart[n], "default")
		m2, pa2, _ := tally(byChart[n], "permissive")
		fmt.Fprintf(&b, "| %s | %d | %.0f%% | %.0f%% |\n", n, total, pct(m, total), pct(m2+pa2, total))
	}
	b.WriteString("\n## By scenario\n\n")
	b.WriteString("\\* Add-only scenarios (`env-add`, `label-add`, `nodeselector-add`, `pod-annotation`, `toleration`) measure the mapping capability; they are not detected alone in a live cluster. Argo CD does not report fields that exist only in the live object (added with `kubectl edit` or `patch` and absent from Git), so such an addition is mapped only when the same resource also has a reported drift. Removals and value changes are always detected.\n\n")
	b.WriteString("| Scenario | Cases | Mapped % (default) | Mapped or partial % (permissive) |\n|---|---|---|---|\n")
	byScenario := map[string][]caseResult{}
	var sids []string
	for _, r := range results {
		if _, ok := byScenario[r.Scenario]; !ok {
			sids = append(sids, r.Scenario)
		}
		byScenario[r.Scenario] = append(byScenario[r.Scenario], r)
	}
	sort.Strings(sids)
	for _, s := range sids {
		m, _, total := tally(byScenario[s], "default")
		m2, pa2, _ := tally(byScenario[s], "permissive")
		fmt.Fprintf(&b, "| %s | %d | %.0f%% | %.0f%% |\n", scenarioLabel(s), total, pct(m, total), pct(m2+pa2, total))
	}
	b.WriteString("\n## Cases\n\n| Chart | Resource | Scenario | Changed fields | default | permissive | no-overrides |\n|---|---|---|---|---|---|---|\n")
	for _, r := range results {
		var paths []string
		for _, c := range r.Changes {
			paths = append(paths, "`"+c.Path+"`")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", r.Chart, r.Resource, scenarioLabel(r.Scenario), strings.Join(paths, "<br>"),
			cellOf(r.ByPolicy["default"]), cellOf(r.ByPolicy["permissive"]), cellOf(r.ByPolicy["no-overrides"]))
	}
	return b.String()
}

func cellOf(o outcome) string {
	switch o.Result {
	case Mapped:
		return "Mapped `" + strings.ReplaceAll(o.Keys, ", ", "`<br>`") + "`"
	case Partial:
		return "Partial `" + strings.ReplaceAll(o.Keys, ", ", "`<br>`") + "` (left out: " + o.Reason + ")"
	}
	return "Unmapped (" + o.Reason + ")"
}

// golden is one line per case and policy: the key of the case and the outcome.
func golden(results []caseResult) string {
	var b strings.Builder
	b.WriteString("# Expected outcomes of make coverage. Regenerate with make coverage-update.\n")
	b.WriteString("# chart | resource | scenario | policy | outcome\n")
	for _, r := range results {
		for _, p := range policySets() {
			fmt.Fprintf(&b, "%s | %s | %s | %s | %s\n", r.Chart, r.Resource, r.Scenario, p.name, r.ByPolicy[p.name])
		}
	}
	return b.String()
}

func parseGolden(s string) map[string]string {
	m := map[string]string{}
	for _, line := range strings.Split(s, "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, " | ", 5)
		if len(parts) != 5 {
			continue
		}
		m[strings.Join(parts[:4], " | ")] = parts[4]
	}
	return m
}

func resultRank(outcome string) int {
	switch {
	case strings.HasPrefix(outcome, Mapped):
		return 2
	case strings.HasPrefix(outcome, Partial):
		return 1
	}
	return 0
}

// compare reports what got worse (a lower result, or a Mapped case that edits
// another key), what got better, and what is new or gone.
func compare(want, got map[string]string) (regressions, improvements, changed []string) {
	for k, w := range want {
		g, ok := got[k]
		switch {
		case !ok:
			changed = append(changed, k+": gone (was "+w+")")
		case g == w:
		case resultRank(g) < resultRank(w):
			regressions = append(regressions, fmt.Sprintf("%s: %s -> %s", k, w, g))
		case resultRank(g) > resultRank(w):
			improvements = append(improvements, fmt.Sprintf("%s: %s -> %s", k, w, g))
		case resultRank(g) == 2: // Mapped, but another edit
			regressions = append(regressions, fmt.Sprintf("%s: the edit changed: %s -> %s", k, w, g))
		default: // same rank, another detail (a reason, the fields left out)
			changed = append(changed, fmt.Sprintf("%s: %s -> %s", k, w, g))
		}
	}
	for k, g := range got {
		if _, ok := want[k]; !ok {
			changed = append(changed, k+": new ("+g+")")
		}
	}
	sort.Strings(regressions)
	sort.Strings(improvements)
	sort.Strings(changed)
	return
}
