package kustomize

import (
	"fmt"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/sserkanml/backflow/api/v1alpha1"
	"github.com/sserkanml/backflow/internal/rendermap"
)

// blocked says why a change cannot be mapped whatever is edited: the Application
// sets the value on top of Git, or the value feeds a hashed generator name.
func (f *finder) blocked(ch v1alpha1.FieldChange) *rendermap.Blocked {
	if opt := f.setByApplication(ch); opt != "" {
		return &rendermap.Blocked{Reason: rendermap.ReasonSetByApplication,
			Message: fmt.Sprintf("set by spec.source.kustomize.%s of Application %s; Git cannot change it", opt, f.pol.Application)}
	}
	if f.origin.Generated {
		if k, name, hashed := f.hashedGenerator(); hashed {
			return &rendermap.Blocked{Reason: rendermap.ReasonValueAffectsOtherFields,
				Message: fmt.Sprintf("%s %q is generated by %s with a name hash: changing its data changes the hash in its name, and with it every field that refers to it; "+
					"set disableNameSuffixHash in generatorOptions or on the generator %q in %s to map the data", f.obj.GetKind(), f.obj.GetName(), name, name, k.file)}
		}
	}
	return nil
}

// setByApplication returns the option of spec.source.kustomize that sets the
// field the change is about, or "".
func (f *finder) setByApplication(ch v1alpha1.FieldChange) string {
	o := f.src.Options
	segs := parseSegments(ch.Path)
	last := ""
	if len(segs) > 0 {
		last = segs[len(segs)-1]
	}
	switch {
	case last == "image" && slices.ContainsFunc(segs, isContainerList):
		if image, ok := scalarJSON(ch.Desired); ok && o.SetsImage(image) != "" {
			return "images"
		}
	case slices.Equal(segs, specReplicas):
		for name := range o.Replicas {
			if name == f.obj.GetName() || name == f.declaredName() || strings.TrimPrefix(strings.TrimSuffix(f.obj.GetName(), o.NameSuffix), o.NamePrefix) == name {
				return keyReplicas
			}
		}
	case slices.Equal(segs, []string{keyMetadata, keyName}):
		if o.NamePrefix != "" {
			return "namePrefix"
		}
		if o.NameSuffix != "" {
			return "nameSuffix"
		}
	case slices.Equal(segs, []string{keyMetadata, keyNamespace}) && o.Namespace != "":
		return keyNamespace
	}
	if key, kind := labelKey(segs); kind == keyLabels {
		if _, ok := o.CommonLabels[key]; ok {
			return "commonLabels"
		}
	} else if kind == keyAnnotations {
		if _, ok := o.CommonAnnotations[key]; ok {
			return "commonAnnotations"
		}
	}
	for _, p := range o.Patches {
		if f.appPatchSets(p, ch, segs) {
			return keyPatches
		}
	}
	return ""
}

// appPatchSets reports whether a patch of the Application sets the field.
func (f *finder) appPatchSets(p AppPatch, ch v1alpha1.FieldChange, segs []string) bool {
	if p.Kind != "" && p.Kind != f.obj.GetKind() {
		return false
	}
	if p.Name != "" && p.Name != f.obj.GetName() && p.Name != f.declaredName() {
		return false
	}
	if p.Patch == "" {
		return false // a file in Git: its edit is a normal candidate
	}
	root, err := parseRoot(p.Patch)
	if err != nil {
		return false
	}
	switch root.Kind {
	case yaml.SequenceNode:
		for _, op := range root.Content {
			if scalarOrEmpty(mapValue(op, "path")) == ch.Path {
				return true
			}
		}
	case yaml.MappingNode:
		d := docOf(root, 0)
		if d.kind != f.obj.GetKind() {
			return false
		}
		steps, ok := stepsOf(f.group, f.obj.Object, segs)
		if !ok {
			return false
		}
		_, _, found := findInPatch(yamlNode{root}, steps)
		return found
	}
	return false
}
