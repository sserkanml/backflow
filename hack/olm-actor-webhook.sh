#!/usr/bin/env bash
#
# Writes docs/olm/actor-webhook.yaml: the Service and the ValidatingWebhookConfiguration of the actor webhook for an
# installation from OperatorHub (OpenShift). They are made from the chart (helm template), so that the rules, the
# matchConditions, the timeout and the failurePolicy are the chart's and not a copy: a ClusterServiceVersion cannot carry this
# webhook, because its webhookdefinitions have no matchConditions (without them every update of every namespaced resource,
# Secrets included, would be sent to the operator). What the chart makes for Kubernetes in general is changed here for the pods
# OLM starts: the Service selects them by the labels of the Deployment of the bundle, and targets the port by number.
#
# The file has two placeholders for the user: OPERATOR_NAMESPACE (where the operator is installed) and WEBHOOK_PATH (a
# random path, which is the secret of the webhook: BACKFLOW_ACTOR_WEBHOOK_PATH has to be the same).
#
#   ./hack/olm-actor-webhook.sh          # writes the file
#   ./hack/olm-actor-webhook.sh --check  # fails if the file is not what the chart makes (CI)
#
# bash 3.2 compatible.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/docs/olm/actor-webhook.yaml"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  cat <<'HEADER'
# Generated by hack/olm-actor-webhook.sh from the Helm chart (make olm-actor-webhook). Do not edit.
#
# The optional actor webhook for an installation from OperatorHub on OpenShift: it records who changed a resource, so that a
# proposal can name the user. See docs/install/openshift.md ("The actor webhook"). Replace OPERATOR_NAMESPACE and WEBHOOK_PATH:
#
#   sed -e 's/OPERATOR_NAMESPACE/openshift-operators/g' -e "s#WEBHOOK_PATH#observe-$(openssl rand -hex 16)#g" actor-webhook.yaml
HEADER
  helm template backflow "$ROOT/charts/backflow" --namespace OPERATOR_NAMESPACE \
    --set actorWebhook.enabled=true --set actorWebhook.tls.mode=serviceCA --set actorWebhook.path=/WEBHOOK_PATH \
    --set serviceAccount.name=backflow-controller-manager --set actorWebhook.networkPolicy.enabled=false \
    --show-only templates/actor-webhook-config.yaml --show-only templates/actor-webhook-service.yaml \
    | sed -e '/^# Source:/d' \
      -e '/helm.sh\/chart:/d' -e '/app.kubernetes.io\/instance: backflow/d' -e '/app.kubernetes.io\/managed-by: Helm/d' \
      -e '/app.kubernetes.io\/version:/d' \
      -e 's#targetPort: actor-webhook#targetPort: 9443#' \
      -e 's#path: "/WEBHOOK_PATH"#path: "/WEBHOOK_PATH"#'
} >"$tmp"

if [[ "${1:-}" == "--check" ]]; then
  diff -u "$OUT" "$tmp" || { echo "docs/olm/actor-webhook.yaml is not what the chart makes: run make olm-actor-webhook" >&2; exit 1; }
  exit 0
fi
cp "$tmp" "$OUT"
echo "wrote $OUT"
