#!/usr/bin/env bash
#
# Writes api/v1beta1 from api/v1: the same Go types under the old version name. backflow.io/v1beta1 stays served for all of 1.x
# (deprecated) with exactly the schema of v1, so it is not a second copy to keep in step by hand: v1 is the source, this makes the
# other, and CI fails when the two differ (make sync-v1beta1 && git diff --exit-code api/v1beta1, and the test that compares the
# generated schemas of the CRDs).
#
#   ./hack/sync-v1beta1.sh
#
# OUT_DIR writes somewhere else (the test that compares). The differences: the package and the version name, and v1beta1 is not the storage version but is deprecated (the API server
# sends the warning to every client that uses it). The tests stay in api/v1; the DeepCopy methods are made by controller-gen.
#
# bash 3.2 compatible.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/api/v1"
DST="${OUT_DIR:-$ROOT/api/v1beta1}"
WARNING='backflow.io/v1beta1 is deprecated, use backflow.io/v1 (the schema is the same). It is served until 2.0.'

mkdir -p "$DST"
find "$DST" -type f -name '*.go' ! -name 'zz_generated.deepcopy.go' -delete
for f in "$SRC"/*.go; do
  base="$(basename "$f")"
  case "$base" in *_test.go | zz_generated.deepcopy.go) continue ;; esac
  {
    printf '// Code generated by hack/sync-v1beta1.sh from api/v1. DO NOT EDIT.\n\n'
    sed -e 's/^package v1$/package v1beta1/' \
      -e 's/^\/\/ Package v1 contains/\/\/ Package v1beta1 contains/' \
      -e 's/Version: "v1"}/Version: "v1beta1"}/' \
      -e "s|^// +kubebuilder:storageversion\$|// +kubebuilder:deprecatedversion:warning=\"$WARNING\"|" \
      "$f"
  } >"$DST/$base"
done
echo "wrote $DST from $SRC"
