#!/usr/bin/env bash
#
# Backflow - values set in the Application, end-to-end test
#
# A drift whose value an option of the Argo CD Application sets (here
# helm.parameters) cannot be proposed to Git: no Argo CD API renders an
# Application with a changed option. Backflow says where the option is defined
# instead, and writes nothing. This script builds an app-of-apps and checks the
# diagnosis in status.mapping.application.
#
# It needs no GITLAB_TOKEN and writes nothing to gitlab.com: the parent
# Application reads its Git repository from a git server pod in the cluster
# (namespace av-git, built from a local repository), and the children deploy the
# public demo chart (helm/demo) of the demo repository, read-only.
#
#   a. Parameter of a Git-managed Application: av-parent (Directory, from the
#      in-cluster repository) defines the Application av-child with
#      helm.parameters config.feature=beta. FEATURE is changed to gamma in the
#      cluster. The proposal is Unmapped (SetByApplication); status.mapping.application
#      names the option, the current value ("beta") and the suggested one
#      ("gamma"), and the parent: Located, the file apps/children/child.yaml, the
#      location, and a diff that changes beta to gamma. No merge request, no branch
#      in the parent repository, one Event with the diagnosis.
#   b. An Application nobody manages (av-orphan): NotManagedFromGit.
#   c. An Application generated by an ApplicationSet (av-set): GeneratedByApplicationSet,
#      naming the ApplicationSet.
#   d. The parent is not synced (the child's parameter was changed in the cluster,
#      so Git no longer says what runs): OutOfSync, no file.
#   e. Secrets: the Argo CD token appears in no operator log line and no proposal.
#
# Requires ./hack/dev-up.sh (Argo CD and the CRDs) and git. The demo
# Applications of the other tests are not touched; the Applications of this one
# carry the label backflow.io/demo=appvalues and not env=test.
#
# Usage (from the repository root):
#   ./hack/test-application-values.sh
#   SECTIONS=a,d ./hack/test-application-values.sh   # only those sections
#   KEEP=true ./hack/test-application-values.sh      # keep what was created
#
# Sections are independent except that d changes the child of a and restores it
# (a failed run is cleaned up on exit).

set -euo pipefail

CLUSTER_NAME="${CLUSTER_NAME:-backflow}"
ARGOCD_NS="${ARGOCD_NS:-argocd}"
NS="${NS:-backflow-appvalues-test}"
GIT_NS="av-git"
POLICY="appvalues-policy"
DEMO_REPO="${DEMO_REPO:-https://gitlab.com/sserkanml/backflow-demo.git}"
TOKEN_SECRET_NS="${TOKEN_SECRET_NS:-backflow-system}"
TOKEN_SECRET="${TOKEN_SECRET:-argocd-token}"
MANAGER_NS="${MANAGER_NS:-backflow-system}"
MANAGER_DEPLOY="${MANAGER_DEPLOY:-backflow-controller-manager}"
KEEP="${KEEP:-false}"
WINDOW="${WINDOW:-10s}"
WAIT="${WAIT:-180}"
SECTIONS="${SECTIONS:-}"

PARENT="av-parent"
CHILD="av-child"
ORPHAN="av-orphan"
SET="av-set"
SET_CHILD="av-set-dev"
CM="demo-helm-config"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG_DIR="$ROOT/tmp"
LOG_FILE="$LOG_DIR/test-application-values-manager.log"

if [[ -t 1 ]]; then
  GREEN=$'\e[32m'; RED=$'\e[31m'; BOLD=$'\e[1m'; NC=$'\e[0m'
else
  GREEN=""; RED=""; BOLD=""; NC=""
fi
PASS=0
FAIL=0
TIMING_NAMES=()
TIMING_SECS=()
SECTION_NAME=""
SECTION_START=$SECONDS
MANAGER_PID=""
PF_PID=""
WORKDIR=""
SUMMARY_PRINTED=false
CHILD_PARAM_CHANGED=false

k() { kubectl --context "kind-$CLUSTER_NAME" "$@"; }
end_section() {
  if [[ -n "$SECTION_NAME" ]]; then
    TIMING_NAMES+=("$SECTION_NAME")
    TIMING_SECS+=("$((SECONDS - SECTION_START))")
  fi
  SECTION_NAME=""
}
step() { end_section; SECTION_NAME="$*"; SECTION_START=$SECONDS; echo; echo "${BOLD}▶ $*${NC}"; }
pass() { echo "  ${GREEN}✔${NC} $*"; PASS=$((PASS + 1)); }
fail() { echo "  ${RED}✘${NC} $*"; FAIL=$((FAIL + 1)); }
die() { echo "${RED}ERROR:${NC} $*" >&2; exit 1; }
section_wanted() { [[ -z "$SECTIONS" || ",$SECTIONS," == *",$1,"* ]]; }
for s in ${SECTIONS//,/ }; do
  case " a b c d e " in *" $s "*) ;; *) echo "SECTIONS: unknown section '$s' (valid: a,b,c,d,e)" >&2; exit 1 ;; esac
done

expect_eq() { if [[ "$3" == "$2" ]]; then pass "$1 = $2"; else fail "$1: expected '$2', got '$3'"; fi; }
expect_contains() { if [[ "$3" == *"$2"* ]]; then pass "$1 contains '$2'"; else fail "$1: expected to contain '$2', got '$3'"; fi; }
expect_empty() { if [[ -z "$2" ]]; then pass "$1 is empty"; else fail "$1: expected empty, got '$2'"; fi; }

wait_for() {
  local desc="$1" waited=0
  shift
  while ! "$@" >/dev/null 2>&1; do
    waited=$((waited + 2))
    if (( waited > WAIT )); then fail "$desc (timed out after ${WAIT}s)"; show_state; return 0; fi
    sleep 2
  done
  pass "$desc"
}
show_state() {
  echo "    proposals:"
  k -n "$NS" get driftproposals -o jsonpath='{range .items[*]}{.metadata.name}{" phase="}{.status.phase}{" Mapped="}{.status.conditions[?(@.type=="Mapped")].reason}{"\n"}{end}' 2>/dev/null | sed 's/^/      /'
  if [[ -f "$LOG_FILE" ]]; then
    echo "    operator:"
    grep -E "Cannot map|Proposal unmapped|Reconciler error" "$LOG_FILE" 2>/dev/null | tail -n 3 | cut -c1-300 | sed 's/^/      /'
  fi
}

print_summary() {
  local aborted="${1:-}"
  SUMMARY_PRINTED=true
  end_section
  echo
  if [[ -n "$aborted" ]]; then echo "${RED}${BOLD}The test stopped early.${NC}"; fi
  echo "${BOLD}Summary:${NC} ${GREEN}$PASS passed${NC}, ${RED}$FAIL failed${NC}"
  local i
  for i in "${!TIMING_NAMES[@]}"; do printf '  %4ss  %s\n' "${TIMING_SECS[$i]}" "${TIMING_NAMES[$i]}"; done
}

cleanup() {
  local status=$?
  set +e
  trap - EXIT
  if [[ -n "$MANAGER_PID" ]] && kill -0 "$MANAGER_PID" 2>/dev/null; then kill "$MANAGER_PID" 2>/dev/null; wait "$MANAGER_PID" 2>/dev/null; fi
  if [[ -n "$PF_PID" ]] && kill -0 "$PF_PID" 2>/dev/null; then kill "$PF_PID" 2>/dev/null; wait "$PF_PID" 2>/dev/null; fi
  if [[ "$KEEP" != "true" ]]; then
    # The ApplicationSet first, so the Application it generated goes with it.
    k -n "$ARGOCD_NS" delete applicationset "$SET" --ignore-not-found --wait=true >/dev/null 2>&1
    k -n "$ARGOCD_NS" delete application "$PARENT" "$CHILD" "$ORPHAN" "$SET_CHILD" --ignore-not-found --wait=false >/dev/null 2>&1
    k delete namespace "$NS" "$GIT_NS" av-child av-orphan av-set --ignore-not-found --wait=false >/dev/null 2>&1
  fi
  if [[ "$SUMMARY_PRINTED" != "true" ]]; then FAIL=$((FAIL + 1)); print_summary aborted; (( status != 0 )) || status=1; fi
  if [[ -n "$WORKDIR" && "$WORKDIR" == *backflow-appvalues-test.* ]]; then rm -rf "$WORKDIR"; fi
  exit "$status"
}
trap cleanup EXIT

app_field() { k -n "$ARGOCD_NS" get application "$1" -o jsonpath="$2" 2>/dev/null; }
synced() { [[ "$(app_field "$1" '{.status.sync.status}')" == "Synced" ]]; }
refresh_app() { k -n "$ARGOCD_NS" annotate application "$1" "argocd.argoproj.io/refresh=${2:-normal}" --overwrite >/dev/null 2>&1 || true; }
live_cm() { k -n "$1" get configmap "$CM" -o jsonpath="{.data.$2}" 2>/dev/null; }
set_cm() { k -n "$1" patch configmap "$CM" --type merge -p "{\"data\":{\"$2\":\"$3\"}}" >/dev/null; refresh_app "$4"; }

dp_field() { k -n "$NS" get driftproposal "$1" -o jsonpath="{$2}" 2>/dev/null; }
# proposal_for <app> <phase>: the name of a proposal of the Application in the phase.
proposal_for() {
  k -n "$NS" get driftproposals -o jsonpath='{range .items[*]}{.metadata.name}|{.status.phase}|{.spec.application.name}{"\n"}{end}' 2>/dev/null |
    awk -F'|' -v a="$1" -v p="$2" '$3 == a && $2 == p { print $1 }' | head -n 1
}
has_proposal() { [[ -n "$(proposal_for "$1" "$2")" ]]; }
# newest_proposal <app>: the Unmapped proposal of the Application that was made last.
newest_proposal() {
  k -n "$NS" get driftproposals --sort-by=.metadata.creationTimestamp -o jsonpath='{range .items[*]}{.metadata.name}|{.status.phase}|{.spec.application.name}{"\n"}{end}' 2>/dev/null |
    awk -F'|' -v a="$1" '$3 == a && $2 == "Unmapped" { last = $1 } END { print last }'
}
app_block() { dp_field "$1" ".status.mapping.application$2"; }

expect_nothing_written() {
  local dp="$1"
  expect_empty "merge request of $dp" "$(dp_field "$dp" .status.mergeRequest.url)"
  expect_eq "strategy of $dp" "Unmapped" "$(dp_field "$dp" .status.mapping.strategy)"
  expect_empty "edits of $dp" "$(dp_field "$dp" '.status.mapping.edits[*].file')"
  expect_eq "branches of the parent repository" "main" "$(repo_branches)"
}
repo_branches() { k -n "$GIT_NS" exec gitserver -- sh -c 'git --git-dir=/srv/repo.git branch --format="%(refname:short)" | tr "\n" " " | sed "s/ $//"' 2>/dev/null; }

cd "$ROOT"

# ---------------------------------------------------------------------------
step "Prerequisites"
for cmd in kubectl make curl python3 git; do command -v "$cmd" >/dev/null || die "'$cmd' not found"; done
k cluster-info >/dev/null 2>&1 || die "cluster kind-$CLUSTER_NAME is not reachable. Run ./hack/dev-up.sh first."
k get crd applications.argoproj.io applicationsets.argoproj.io >/dev/null 2>&1 || die "Argo CD is not installed. Run ./hack/dev-up.sh first."
k -n "$TOKEN_SECRET_NS" get secret "$TOKEN_SECRET" >/dev/null 2>&1 || die "Secret $TOKEN_SECRET_NS/$TOKEN_SECRET not found. Run ./hack/dev-up.sh first."
if curl -fs -o /dev/null http://localhost:8081/healthz 2>/dev/null; then die "An operator is already running on port 8081 (probably 'make run'). Stop it first."; fi
if [[ "$(k -n "$MANAGER_NS" get deployment "$MANAGER_DEPLOY" -o jsonpath='{.status.readyReplicas}' 2>/dev/null)" =~ ^[1-9] ]]; then
  die "The operator is deployed in the cluster and would race the local one. Run: kubectl -n $MANAGER_NS scale deploy/$MANAGER_DEPLOY --replicas=0"
fi
for ns in "$NS" "$GIT_NS" av-child av-orphan av-set; do
  [[ -z "$(k get namespace "$ns" -o name 2>/dev/null)" ]] || die "namespace $ns exists (an earlier run?). Delete it first."
done
pass "cluster, Argo CD and git are available"
WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/backflow-appvalues-test.XXXXXX")"
chmod 700 "$WORKDIR"

# ---------------------------------------------------------------------------
step "The parent's Git repository: a git server pod in the cluster"
mkdir -p "$WORKDIR/work/apps/children"
cat >"$WORKDIR/work/apps/children/child.yaml" <<EOF
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: $CHILD
  namespace: $ARGOCD_NS
  labels:
    backflow.io/demo: appvalues
spec:
  project: default
  source:
    repoURL: $DEMO_REPO
    targetRevision: main
    path: helm/demo
    helm:
      valueFiles:
        - values-dev.yaml
      parameters:
        - name: config.feature
          value: beta
  destination:
    server: https://kubernetes.default.svc
    namespace: av-child
  syncPolicy:
    automated: {}
    syncOptions:
      - CreateNamespace=true
EOF
(
  cd "$WORKDIR/work"
  git init -q -b main .
  git add -A
  git -c user.email=test@example.com -c user.name=test commit -q -m "the parent defines the child"
  cd "$WORKDIR"
  git clone -q --bare work repo.git
  (cd repo.git && git update-server-info)
  tar czf repo.tgz -C repo.git .
)
k create namespace "$GIT_NS" >/dev/null
k -n "$GIT_NS" create configmap repo --from-file=repo.tgz="$WORKDIR/repo.tgz" >/dev/null
k apply -n "$GIT_NS" -f - >/dev/null <<'YAML'
apiVersion: v1
kind: Pod
metadata: {name: gitserver, labels: {app: gitserver}}
spec:
  containers:
  - name: git
    image: alpine:3
    command:
    - sh
    - -c
    - |
      apk add --no-cache git git-daemon lighttpd >/dev/null
      git config --system safe.directory '*'
      mkdir -p /srv/repo.git && tar xzf /data/repo.tgz -C /srv/repo.git
      cat > /etc/lighttpd/git.conf <<'CONF'
      server.modules = ("mod_alias", "mod_cgi", "mod_setenv")
      server.document-root = "/srv"
      server.port = 8080
      alias.url = ("/git" => "/usr/libexec/git-core/git-http-backend")
      $HTTP["url"] =~ "^/git" {
        cgi.assign = ("" => "")
        setenv.add-environment = ("GIT_PROJECT_ROOT" => "/srv", "GIT_HTTP_EXPORT_ALL" => "1")
      }
      CONF
      exec lighttpd -D -f /etc/lighttpd/git.conf
    volumeMounts: [{name: data, mountPath: /data}]
    readinessProbe: {tcpSocket: {port: 8080}, periodSeconds: 2}
  volumes: [{name: data, configMap: {name: repo}}]
---
apiVersion: v1
kind: Service
metadata: {name: gitserver}
spec: {selector: {app: gitserver}, ports: [{port: 8080}]}
YAML
wait_for "the git server is ready" k -n "$GIT_NS" wait pod/gitserver --for=condition=Ready --timeout=1s
REPO_URL="http://gitserver.$GIT_NS.svc:8080/git/repo.git"
expect_eq "branches of the parent repository" "main" "$(repo_branches)"
MAIN_SHA="$(k -n "$GIT_NS" exec gitserver -- git --git-dir=/srv/repo.git rev-parse main 2>/dev/null)"

# ---------------------------------------------------------------------------
step "Operator, policy and the app-of-apps"
PF_PORT="$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1",0)); print(s.getsockname()[1])')"
kubectl --context "kind-$CLUSTER_NAME" -n "$ARGOCD_NS" port-forward svc/argocd-server "$PF_PORT":443 >/dev/null 2>&1 &
PF_PID=$!
for _ in $(seq 1 30); do
  curl -ksf -o /dev/null "https://localhost:$PF_PORT/api/version" && break
  kill -0 "$PF_PID" 2>/dev/null || die "port-forward exited"
  sleep 1
done
make manifests install >/dev/null
make build >/dev/null
mkdir -p "$LOG_DIR"
"$ROOT/bin/manager" >"$LOG_FILE" 2>&1 &
MANAGER_PID=$!
for _ in $(seq 1 60); do
  curl -fs -o /dev/null http://localhost:8081/readyz 2>/dev/null && break
  kill -0 "$MANAGER_PID" 2>/dev/null || die "operator exited, log: $LOG_FILE"
  sleep 1
done
curl -fs -o /dev/null http://localhost:8081/readyz || die "operator did not become ready, log: $LOG_FILE"

k create namespace "$NS" >/dev/null
ARGO_TOKEN="$(k -n "$TOKEN_SECRET_NS" get secret "$TOKEN_SECRET" -o jsonpath='{.data.token}' | base64 -d)"
k -n "$NS" create secret generic argocd-token --from-literal=token="$ARGO_TOKEN" >/dev/null
# The token is only needed again to check that it is nowhere it must not be.
printf '%s' "$ARGO_TOKEN" >"$WORKDIR/argo-token"
chmod 600 "$WORKDIR/argo-token"
ARGO_TOKEN=""
# ReportOnly: the diagnosis happens while mapping, and nothing may be proposed anyway.
k apply -f - >/dev/null <<YAML
apiVersion: backflow.io/v1alpha1
kind: BackflowPolicy
metadata:
  name: $POLICY
  namespace: $NS
spec:
  argoCDNamespace: $ARGOCD_NS
  mode: ReportOnly
  batchWindow: $WINDOW
  applications:
    selector:
      matchLabels:
        backflow.io/demo: appvalues
  argoCD:
    url: https://localhost:$PF_PORT
    insecureSkipTLSVerify: true
    tokenSecretRef:
      name: argocd-token
      key: token
YAML
wait_for "the policy is Ready" k -n "$NS" wait "bfp/$POLICY" --for=condition=Ready --timeout=1s

k apply -f - >/dev/null <<YAML
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: $PARENT
  namespace: $ARGOCD_NS
spec:
  project: default
  source:
    repoURL: $REPO_URL
    targetRevision: main
    path: apps/children
  destination:
    server: https://kubernetes.default.svc
    namespace: $ARGOCD_NS
  syncPolicy:
    automated: {}
YAML
wait_for "$PARENT is Synced" synced "$PARENT"
wait_for "$CHILD exists and is Synced" synced "$CHILD"
expect_eq "tracking-id of $CHILD" "$PARENT:argoproj.io/Application:$ARGOCD_NS/$CHILD" "$(app_field "$CHILD" '{.metadata.annotations.argocd\.argoproj\.io/tracking-id}')"
test_outofsync() { [[ "$(app_field "$1" '{.status.sync.status}')" == "OutOfSync" ]]; }
newer_proposal() { local n; n="$(newest_proposal "$CHILD")"; [[ -n "$n" && "$n" != "${1:-}" ]]; }
feature_is() { [[ "$(live_cm "$1" FEATURE)" == "$2" ]]; }
wait_for "$CHILD renders FEATURE=beta" feature_is av-child beta
tracked() { k -n "$NS" get bfp "$POLICY" -o jsonpath='{.status.matchedApplications[*]}' | tr ' ' '\n' | grep -qx "$1"; }
wait_for "the policy tracks $CHILD" tracked "$CHILD"

# ---------------------------------------------------------------------------
if section_wanted a; then
step "a. A parameter of an Application that Git defines: the diagnosis names the file, and nothing is written"
require_change() { [[ "$1" != "$2" ]] || die "section $3: $1 is both the Git and the new value; there would be no drift"; }
LIVE_FEATURE="$(live_cm av-child FEATURE)"
NEW_FEATURE="gamma"
require_change "$LIVE_FEATURE" "$NEW_FEATURE" a
set_cm av-child FEATURE "$NEW_FEATURE" "$CHILD"
wait_for "proposal is Unmapped (FEATURE $LIVE_FEATURE -> $NEW_FEATURE)" has_proposal "$CHILD" Unmapped
P_A="$(proposal_for "$CHILD" Unmapped)"
if [[ -n "$P_A" ]]; then
  expect_eq "Mapped reason" "SetByApplication" "$(dp_field "$P_A" '.status.conditions[?(@.type=="Mapped")].reason')"
  expect_eq "child Application" "$ARGOCD_NS/$CHILD" "$(app_block "$P_A" .application)"
  expect_eq "option" "spec.source.helm.parameters[name=config.feature]" "$(app_block "$P_A" .option)"
  expect_eq "option path" "/spec/source/helm/parameters/0/value" "$(app_block "$P_A" .optionPath)"
  expect_eq "current value" '"beta"' "$(app_block "$P_A" .current)"
  expect_eq "suggested value" "\"$NEW_FEATURE\"" "$(app_block "$P_A" .suggested)"
  expect_eq "parent state" "Located" "$(app_block "$P_A" .parent.state)"
  expect_eq "parent" "$ARGOCD_NS/$PARENT" "$(app_block "$P_A" .parent.name)"
  expect_eq "parent file" "apps/children/child.yaml" "$(app_block "$P_A" .parent.file)"
  expect_eq "parent location" "/spec/source/helm/parameters/0/value" "$(app_block "$P_A" .parent.location)"
  expect_eq "parent revision" "$MAIN_SHA" "$(app_block "$P_A" .parent.revision)"
  DIFF_A="$(app_block "$P_A" .parent.diff)"
  expect_contains "parent diff" "-          value: beta" "$DIFF_A"
  expect_contains "parent diff" "+          value: $NEW_FEATURE" "$DIFF_A"
  MSG_A="$(dp_field "$P_A" '.status.conditions[?(@.type=="Mapped")].message')"
  expect_eq "message" "Set by spec.source.helm.parameters[name=config.feature] of Application $ARGOCD_NS/$CHILD, defined in apps/children/child.yaml (parent $ARGOCD_NS/$PARENT). Set it to \"$NEW_FEATURE\" there; Backflow cannot verify an Application option by rendering, so no merge request is made." "$MSG_A"
  expect_nothing_written "$P_A"
  expect_eq "main of the parent repository" "$MAIN_SHA" "$(k -n "$GIT_NS" exec gitserver -- git --git-dir=/srv/repo.git rev-parse main 2>/dev/null)"
  EVENTS_A="$(k -n "$NS" get events --field-selector "involvedObject.name=$P_A,reason=ApplicationValue" -o jsonpath='{range .items[*]}{.note}{"\n"}{end}' 2>/dev/null)"
  expect_contains "the Event of the proposal" "Set by spec.source.helm.parameters[name=config.feature]" "$EVENTS_A"
  expect_eq "Events with that reason for the proposal" "1" "$(printf '%s\n' "$EVENTS_A" | grep -c . || true)"
fi
set_cm av-child FEATURE "$LIVE_FEATURE" "$CHILD"

fi

# ---------------------------------------------------------------------------
if section_wanted b; then
step "b. An Application nobody manages: it is not managed from Git"
k apply -f - >/dev/null <<YAML
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: $ORPHAN
  namespace: $ARGOCD_NS
  labels:
    backflow.io/demo: appvalues
spec:
  project: default
  source:
    repoURL: $DEMO_REPO
    targetRevision: main
    path: helm/demo
    helm:
      valueFiles: [values-dev.yaml]
      parameters:
        - {name: config.feature, value: beta}
  destination:
    server: https://kubernetes.default.svc
    namespace: av-orphan
  syncPolicy:
    automated: {}
    syncOptions: [CreateNamespace=true]
YAML
wait_for "$ORPHAN is Synced" synced "$ORPHAN"
wait_for "$ORPHAN renders FEATURE=beta" feature_is av-orphan beta
wait_for "the policy tracks $ORPHAN" tracked "$ORPHAN"
set_cm av-orphan FEATURE delta "$ORPHAN"
wait_for "proposal is Unmapped" has_proposal "$ORPHAN" Unmapped
P_B="$(proposal_for "$ORPHAN" Unmapped)"
if [[ -n "$P_B" ]]; then
  expect_eq "Mapped reason" "SetByApplication" "$(dp_field "$P_B" '.status.conditions[?(@.type=="Mapped")].reason')"
  expect_eq "parent state" "NotManagedFromGit" "$(app_block "$P_B" .parent.state)"
  expect_empty "parent file" "$(app_block "$P_B" .parent.file)"
  expect_eq "suggested value" '"delta"' "$(app_block "$P_B" .suggested)"
  expect_contains "message" "Application $ARGOCD_NS/$ORPHAN, which is not managed from Git. " "$(dp_field "$P_B" '.status.conditions[?(@.type=="Mapped")].message')"
  expect_nothing_written "$P_B"
fi

fi

# ---------------------------------------------------------------------------
if section_wanted c; then
step "c. An Application generated by an ApplicationSet: the ApplicationSet is named"
k apply -f - >/dev/null <<YAML
apiVersion: argoproj.io/v1alpha1
kind: ApplicationSet
metadata:
  name: $SET
  namespace: $ARGOCD_NS
spec:
  generators:
    - list:
        elements:
          - env: dev
  template:
    metadata:
      name: '$SET-{{env}}'
      labels:
        backflow.io/demo: appvalues
    spec:
      project: default
      source:
        repoURL: $DEMO_REPO
        targetRevision: main
        path: helm/demo
        helm:
          valueFiles: [values-dev.yaml]
          parameters:
            - {name: config.feature, value: beta}
      destination:
        server: https://kubernetes.default.svc
        namespace: av-set
      syncPolicy:
        automated: {}
        syncOptions: [CreateNamespace=true]
YAML
wait_for "$SET_CHILD is Synced" synced "$SET_CHILD"
wait_for "$SET_CHILD renders FEATURE=beta" feature_is av-set beta
wait_for "the policy tracks $SET_CHILD" tracked "$SET_CHILD"
set_cm av-set FEATURE delta "$SET_CHILD"
wait_for "proposal is Unmapped" has_proposal "$SET_CHILD" Unmapped
P_C="$(proposal_for "$SET_CHILD" Unmapped)"
if [[ -n "$P_C" ]]; then
  expect_eq "Mapped reason" "SetByApplication" "$(dp_field "$P_C" '.status.conditions[?(@.type=="Mapped")].reason')"
  expect_eq "parent state" "GeneratedByApplicationSet" "$(app_block "$P_C" .parent.state)"
  expect_eq "ApplicationSet" "$ARGOCD_NS/$SET" "$(app_block "$P_C" .parent.name)"
  expect_contains "message" "generated by ApplicationSet $ARGOCD_NS/$SET. " "$(dp_field "$P_C" '.status.conditions[?(@.type=="Mapped")].message')"
  expect_nothing_written "$P_C"
fi

fi

# ---------------------------------------------------------------------------
