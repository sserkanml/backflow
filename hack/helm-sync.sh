#!/usr/bin/env bash
#
# Keep the Helm chart in step with what `make manifests` generates:
#   - charts/backflow/crds/*.yaml                 <- the config/crd/bases/*.yaml that config/crd/kustomization.yaml lists
#   - charts/backflow/templates/clusterrole.yaml  <- rules of config/rbac/role.yaml, except the one on
#                                                    Secrets, which is a cluster-wide rule unless
#                                                    secretNamespaces is set
#   - charts/backflow/templates/actor-webhook-role.yaml <- the rule on changerecords, as a Role in the
#                                                    release namespace (only with actorWebhook.enabled)
#   - charts/backflow/templates/secrets-role.yaml <- that Secrets rule, as a Role and RoleBinding in
#                                                    each of secretNamespaces
#   - charts/backflow/templates/_actor_conditions.tpl <- the match conditions of the actor webhook,
#                                                    from internal/actorwebhook
#   - charts/backflow/templates/leader-election-role.yaml
#                                                 <- rules of config/rbac/leader_election_role.yaml
#
# Run it through `make helm-sync` (which runs `make manifests` first). CI runs
# the same and fails when the chart changes.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHART="$ROOT/charts/backflow"

# rules <file>: the "rules:" block of a generated RBAC manifest.
rules() { sed -n '/^rules:/,$p' "$1"; }

# rules_of <file> <only|except> [resources]: the "rules:" block with only the rules on
# one of the resources (default secrets; a comma-separated list), or with all the others.
rules_of() {
  rules "$1" | awk -v mode="$2" -v res="${3:-secrets}" '
    BEGIN { n = split(res, want, ",") }
    function matches(b,    i) {
      for (i = 1; i <= n; i++) if (b ~ ("\n  - " want[i] "\n")) return 1
      return 0
    }
    function flush() {
      if (blk != "" && (matches(blk) == (mode == "only"))) printf "%s", blk
      blk = ""
    }
    /^rules:/ { print; next }
    /^- / { flush() }
    { blk = blk $0 "\n" }
    END { flush() }'
}

# CRDs: copied as they are, but only the ones config/crd/kustomization.yaml lists (those are the CRDs of the operator;
# a stray file that controller-gen made from some other package is not), and each must have a group and a name that ends
# in it: Helm applies crds/ on install, and the API server rejects a CRD without one, so the chart could not be installed.
# Helm installs the crds/ directory before the templates and never changes it afterwards.
mkdir -p "$CHART/crds"
find "$CHART/crds" -type f -name '*.yaml' -delete
crds="$(sed -n 's#^[[:space:]]*-[[:space:]]*bases/\(.*\.yaml\)[[:space:]]*$#\1#p' "$ROOT/config/crd/kustomization.yaml")"
[[ -n "$crds" ]] || { echo "config/crd/kustomization.yaml lists no CRD" >&2; exit 1; }
for name in $crds; do
  crd="$ROOT/config/crd/bases/$name"
  [[ -f "$crd" ]] || { echo "config/crd/kustomization.yaml lists bases/$name, which does not exist (make manifests)" >&2; exit 1; }
  group="$(sed -n 's/^  group: *//p' "$crd" | head -1)"
  crd_name="$(sed -n 's/^  name: *//p' "$crd" | head -1)"
  if [[ -z "$group" || "$crd_name" != *".$group" ]]; then
    echo "$name: the CRD has the group '$group' and the name '$crd_name'; a CRD needs a group and a name that ends in it" >&2
    exit 1
  fi
  cp "$crd" "$CHART/crds/$name"
done

{
  cat <<'HEADER'
# Generated by hack/helm-sync.sh from config/rbac/role.yaml (make helm-sync). Do not edit.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ include "backflow.managerName" . }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
HEADER
  # The ChangeRecords of the actor webhook are in the operator's namespace only: a Role (actor-webhook-role.yaml).
  rules_of "$ROOT/config/rbac/role.yaml" except secrets,changerecords
  # Reading Secrets is cluster-wide by default; with secretNamespaces it is
  # granted by a Role in each of those namespaces instead (secrets-role.yaml).
  echo '{{- if not .Values.secretNamespaces }}'
  rules_of "$ROOT/config/rbac/role.yaml" only | sed '1d'
  echo '{{- end }}'
} >"$CHART/templates/clusterrole.yaml"

{
  cat <<'HEADER'
{{- if .Values.secretNamespaces }}
# Generated by hack/helm-sync.sh from config/rbac/role.yaml (make helm-sync). Do not edit.
# The namespaces of secretNamespaces, the release namespace (the Argo CD token) and the
# namespace of argocd.tokenSecret (the token of the operator's default Argo CD connection).
{{- $namespaces := append (without .Values.secretNamespaces .Release.Namespace) .Release.Namespace }}
{{- with .Values.argocd.tokenSecret.namespace }}{{ $namespaces = append $namespaces . }}{{ end }}
{{- $namespaces = uniq $namespaces }}
{{- range $namespaces }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ include "backflow.managerName" $ }}-secrets
  namespace: {{ . }}
  labels:
    {{- include "backflow.labels" $ | nindent 4 }}
HEADER
  rules_of "$ROOT/config/rbac/role.yaml" only
  cat <<'HEADER'
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: {{ include "backflow.managerName" $ }}-secrets
  namespace: {{ . }}
  labels:
    {{- include "backflow.labels" $ | nindent 4 }}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: {{ include "backflow.managerName" $ }}-secrets
subjects:
  - kind: ServiceAccount
    name: {{ include "backflow.serviceAccountName" $ }}
    namespace: {{ $.Release.Namespace }}
{{- end }}
{{- end }}
HEADER
} >"$CHART/templates/secrets-role.yaml"

{
  cat <<'HEADER'
{{- if .Values.leaderElection }}
# Generated by hack/helm-sync.sh from config/rbac/leader_election_role.yaml (make helm-sync). Do not edit.
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ include "backflow.managerName" . }}-leader-election
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
HEADER
  rules "$ROOT/config/rbac/leader_election_role.yaml"
  echo '{{- end }}'
} >"$CHART/templates/leader-election-role.yaml"

{
  cat <<'HEADER'
{{- if .Values.actorWebhook.enabled }}
# Generated by hack/helm-sync.sh from config/rbac/role.yaml (make helm-sync). Do not edit.
# The ChangeRecords live in the release namespace; the operator needs nothing cluster-wide for them.
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ include "backflow.managerName" . }}-changerecords
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
HEADER
  rules_of "$ROOT/config/rbac/role.yaml" only changerecords
  cat <<'HEADER'
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: {{ include "backflow.managerName" . }}-changerecords
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: {{ include "backflow.managerName" . }}-changerecords
subjects:
  - kind: ServiceAccount
    name: {{ include "backflow.serviceAccountName" . }}
    namespace: {{ .Release.Namespace }}
{{- end }}
HEADER
} >"$CHART/templates/actor-webhook-role.yaml"

# The match conditions of the actor webhook come from the code that is tested against them.
(cd "$ROOT" && go run ./hack/genactorconditions) >"$CHART/templates/_actor_conditions.tpl"

echo "charts/backflow synced with config/"
