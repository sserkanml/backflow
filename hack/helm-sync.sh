#!/usr/bin/env bash
#
# Keep the Helm chart in step with what `make manifests` generates:
#   - charts/backflow/crds/*.yaml                 <- config/crd/bases/*.yaml
#   - charts/backflow/templates/clusterrole.yaml  <- rules of config/rbac/role.yaml, except the one on
#                                                    Secrets, which is a cluster-wide rule unless
#                                                    secretNamespaces is set
#   - charts/backflow/templates/secrets-role.yaml <- that Secrets rule, as a Role and RoleBinding in
#                                                    each of secretNamespaces
#   - charts/backflow/templates/leader-election-role.yaml
#                                                 <- rules of config/rbac/leader_election_role.yaml
#
# Run it through `make helm-sync` (which runs `make manifests` first). CI runs
# the same and fails when the chart changes.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHART="$ROOT/charts/backflow"

# rules <file>: the "rules:" block of a generated RBAC manifest.
rules() { sed -n '/^rules:/,$p' "$1"; }

# rules_of <file> <only|except>: the "rules:" block with only the rules on
# Secrets, or with all the others.
rules_of() {
  rules "$1" | awk -v mode="$2" '
    function flush() {
      if (blk != "" && ((blk ~ /\n  - secrets\n/) == (mode == "only"))) printf "%s", blk
      blk = ""
    }
    /^rules:/ { print; next }
    /^- / { flush() }
    { blk = blk $0 "\n" }
    END { flush() }'
}

# CRDs: copied as they are. Helm installs the crds/ directory before the
# templates and never changes it afterwards.
mkdir -p "$CHART/crds"
find "$CHART/crds" -type f -name '*.yaml' -delete
for crd in "$ROOT"/config/crd/bases/*.yaml; do
  cp "$crd" "$CHART/crds/$(basename "$crd")"
done

{
  cat <<'HEADER'
# Generated by hack/helm-sync.sh from config/rbac/role.yaml (make helm-sync). Do not edit.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: {{ include "backflow.managerName" . }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
HEADER
  rules_of "$ROOT/config/rbac/role.yaml" except
  # Reading Secrets is cluster-wide by default; with secretNamespaces it is
  # granted by a Role in each of those namespaces instead (secrets-role.yaml).
  echo '{{- if not .Values.secretNamespaces }}'
  rules_of "$ROOT/config/rbac/role.yaml" only | sed '1d'
  echo '{{- end }}'
} >"$CHART/templates/clusterrole.yaml"

{
  cat <<'HEADER'
{{- if .Values.secretNamespaces }}
# Generated by hack/helm-sync.sh from config/rbac/role.yaml (make helm-sync). Do not edit.
# The namespaces of secretNamespaces and the release namespace (the Argo CD token).
{{- $namespaces := append (without .Values.secretNamespaces .Release.Namespace) .Release.Namespace | uniq }}
{{- range $namespaces }}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ include "backflow.managerName" $ }}-secrets
  namespace: {{ . }}
  labels:
    {{- include "backflow.labels" $ | nindent 4 }}
HEADER
  rules_of "$ROOT/config/rbac/role.yaml" only
  cat <<'HEADER'
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: {{ include "backflow.managerName" $ }}-secrets
  namespace: {{ . }}
  labels:
    {{- include "backflow.labels" $ | nindent 4 }}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: Role
  name: {{ include "backflow.managerName" $ }}-secrets
subjects:
  - kind: ServiceAccount
    name: {{ include "backflow.serviceAccountName" $ }}
    namespace: {{ $.Release.Namespace }}
{{- end }}
{{- end }}
HEADER
} >"$CHART/templates/secrets-role.yaml"

{
  cat <<'HEADER'
{{- if .Values.leaderElection }}
# Generated by hack/helm-sync.sh from config/rbac/leader_election_role.yaml (make helm-sync). Do not edit.
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {{ include "backflow.managerName" . }}-leader-election
  namespace: {{ .Release.Namespace }}
  labels:
    {{- include "backflow.labels" . | nindent 4 }}
HEADER
  rules "$ROOT/config/rbac/leader_election_role.yaml"
  echo '{{- end }}'
} >"$CHART/templates/leader-election-role.yaml"

echo "charts/backflow synced with config/"
