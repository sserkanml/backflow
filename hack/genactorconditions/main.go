// Command genactorconditions writes the match conditions of the actor webhook as a Helm
// template, from internal/actorwebhook, so that the chart and the code cannot disagree.
// hack/helm-sync.sh runs it.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/sserkanml/backflow/internal/actorwebhook"
)

const (
	marker  = "__USERS_CLAUSE__"
	keyName = "name"
)

func main() {
	config := flag.Bool("config", false,
		"print a ValidatingWebhookConfiguration (JSON) for a webhook at --url, for the e2e scripts, "+
			"instead of the chart template")
	name := flag.String("name", "backflow-actor-e2e", "its name")
	url := flag.String("url", "", "the URL the API server calls")
	ca := flag.String("ca-bundle", "", "the CA bundle (base64)")
	namespace := flag.String("namespace", "", "the only namespace whose resources are sent to it")
	users := flag.String("exclude-users", "", "comma-separated user names whose changes are not sent")
	flag.Parse()
	if *config {
		printConfig(*name, *url, *ca, *namespace, *users)
		return
	}
	var b strings.Builder
	b.WriteString("{{- /* Generated by hack/genactorconditions from internal/actorwebhook (make helm-sync).")
	b.WriteString(" Do not edit. */ -}}\n")
	b.WriteString("{{- define \"backflow.actorConditions\" -}}\n")
	b.WriteString("{{- $users := .users -}}\n")
	b.WriteString("{{- $clause := \"true\" -}}\n")
	b.WriteString("{{- if $users }}{{ $clause = printf \"!(request.userInfo.username in [%s])\" $users }}{{ end -}}\n")
	for _, c := range actorwebhook.ConditionsWith(marker) {
		var enc strings.Builder
		e := json.NewEncoder(&enc)
		e.SetEscapeHTML(false)
		_ = e.Encode(c.Expression)
		quoted := strings.TrimSpace(enc.String())
		expr := strings.ReplaceAll(quoted, marker, `" $clause "`)
		if strings.Contains(expr, `" $clause "`) {
			expr = "{{ print " + expr + " | toJson }}"
		} else {
			expr = quoted
		}
		fmt.Fprintf(&b, "- name: %s\n  expression: %s\n", c.Name, expr)
	}
	b.WriteString("{{- end }}\n")
	if _, err := os.Stdout.WriteString(b.String()); err != nil {
		os.Exit(1)
	}
}

// printConfig prints a webhook configuration like the chart's, for one namespace and a URL.
func printConfig(name, url, ca, namespace, users string) {
	var excluded []string
	for u := range strings.SplitSeq(users, ",") {
		if u = strings.TrimSpace(u); u != "" {
			excluded = append(excluded, u)
		}
	}
	all := actorwebhook.Conditions(excluded)
	conds := make([]map[string]string, 0, len(all))
	for _, c := range all {
		conds = append(conds, map[string]string{keyName: c.Name, "expression": c.Expression})
	}
	cfg := map[string]any{
		"apiVersion": "admissionregistration.k8s.io/v1", "kind": "ValidatingWebhookConfiguration",
		"metadata": map[string]any{keyName: name},
		"webhooks": []any{map[string]any{
			keyName: "actor.backflow.io", "admissionReviewVersions": []string{"v1"}, "sideEffects": "None",
			"failurePolicy": "Ignore", "timeoutSeconds": 1,
			"namespaceSelector": map[string]any{"matchLabels": map[string]string{"kubernetes.io/metadata.name": namespace}},
			"rules": []any{map[string]any{
				"apiGroups": []string{"*"}, "apiVersions": []string{"*"}, "operations": []string{"UPDATE"},
				"resources": []string{"*", "*/scale"}, "scope": "Namespaced",
			}},
			"matchConditions": conds,
			"clientConfig":    map[string]any{"url": url, "caBundle": ca},
		}},
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(cfg); err != nil {
		os.Exit(1)
	}
}
