// Command genactorconditions writes the match conditions of the actor webhook as a Helm
// template, from internal/actorwebhook, so that the chart and the code cannot disagree.
// hack/helm-sync.sh runs it.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/sserkanml/backflow/internal/actorwebhook"
)

const marker = "__USERS_CLAUSE__"

func main() {
	var b strings.Builder
	b.WriteString("{{- /* Generated by hack/genactorconditions from internal/actorwebhook (make helm-sync).")
	b.WriteString(" Do not edit. */ -}}\n")
	b.WriteString("{{- define \"backflow.actorConditions\" -}}\n")
	b.WriteString("{{- $users := .users -}}\n")
	b.WriteString("{{- $clause := \"true\" -}}\n")
	b.WriteString("{{- if $users }}{{ $clause = printf \"!(request.userInfo.username in [%s])\" $users }}{{ end -}}\n")
	for _, c := range actorwebhook.ConditionsWith(marker) {
		var enc strings.Builder
		e := json.NewEncoder(&enc)
		e.SetEscapeHTML(false)
		_ = e.Encode(c.Expression)
		quoted := strings.TrimSpace(enc.String())
		expr := strings.ReplaceAll(quoted, marker, `" $clause "`)
		if strings.Contains(expr, `" $clause "`) {
			expr = "{{ print " + expr + " | toJson }}"
		} else {
			expr = quoted
		}
		fmt.Fprintf(&b, "- name: %s\n  expression: %s\n", c.Name, expr)
	}
	b.WriteString("{{- end }}\n")
	if _, err := os.Stdout.WriteString(b.String()); err != nil {
		os.Exit(1)
	}
}
